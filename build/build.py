#!/usr/bin/env python3
"""Package yewee into an app bundle / folder.

    python build/build.py                       # internal build (everything)
    python build/build.py --distribution        # what you sell
    python build/build.py --print-version       # the version it would stamp

A distribution build bakes in your licence public key, switches on the
72-hour trial, and leaves out anything that may not be redistributed
(currently the GPL-3.0 RVM model) — see docs/DISTRIBUTION.md.

Signing and notarisation are *not* done here; see build/README.md.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
BUILDINFO = ROOT / "yewee" / "_buildinfo.py"
NOTICES = BUILD / "THIRD-PARTY-NOTICES.txt"

# The public half of the vendor signing key — safe to commit, and the whole
# point of it is to be published. It lives here rather than in an environment
# variable because a distribution build carrying the wrong key produces
# software that looks perfect and cannot be activated by anybody, and that is
# not a mistake you want resting on remembering to export a shell variable.
# The private half never leaves the Licence Admin's data directory.
VENDOR_PUBLIC_KEY = "409208784ace937f8ac9687aa489315f45aa6e2cba33466d3a0d21f695ac9ae2"


def source_version() -> str:
    """yewee/__init__.py's __version__, read as text so building never
    imports the app (and its OpenCV/NDI dependencies) into this process."""
    text = (ROOT / "yewee" / "__init__.py").read_text(encoding="utf-8")
    m = re.search(r'^__version__\s*=\s*"([^"]+)"', text, re.M)
    if not m:
        raise SystemExit("yewee/__init__.py has no __version__")
    return m.group(1)


def write_buildinfo(distribution: bool, pubkey: str, version: str) -> None:
    # BUILD_DATE is when this build was made, compared against a shop
    # licence's update window (maintUntil). It is baked in rather than read
    # off the filesystem, where anyone could change it.
    # UTF-8 explicitly: written in Windows' default cp1252, the docstring's
    # dash is a byte Python will not compile, and PyInstaller then quietly
    # leaves the whole module out (see the check after PyInstaller runs).
    BUILDINFO.write_text(
        '"""Generated by build/build.py — do not edit or commit."""\n'
        f"DISTRIBUTION = {bool(distribution)!r}\n"
        f'VENDOR_PUBLIC_KEY = {pubkey!r}\n'
        f'VERSION = {version!r}\n'
        f"BUILD_DATE = {int(time.time())}\n",
        encoding="utf-8",
    )


def third_party_notices() -> str:
    """THIRD-PARTY-NOTICES.txt's text, generated by `python -m yewee.notices`
    in a child process so the build never imports the app.

    The child is told to speak UTF-8 and its bytes are decoded here as UTF-8.
    A child left to its own devices writes a pipe in the locale's encoding —
    cp1252 on Windows — and reading that as UTF-8 failed the Windows release
    build on the header's dash (0x97). Raises RuntimeError with a readable
    message, never a bare decode error or a TypeError on a None stdout.
    """
    env = dict(os.environ, PYTHONUTF8="1", PYTHONIOENCODING="utf-8")
    proc = subprocess.run([sys.executable, "-X", "utf8", "-m", "yewee.notices"],
                          cwd=ROOT, env=env, capture_output=True)
    err = (proc.stderr or b"").decode("utf-8", errors="replace")
    if proc.returncode != 0:
        raise RuntimeError(f"yewee.notices exited {proc.returncode}:\n{err}")
    try:
        text = (proc.stdout or b"").decode("utf-8")
    except UnicodeDecodeError as e:
        raise RuntimeError(f"yewee.notices wrote something that is not UTF-8 "
                           f"({e}).\n{err}") from None
    if "Vizrt NDI AB" not in text:
        raise RuntimeError("yewee.notices' output has no NDI notice "
                           f"({len(text)} characters).\n{err}")
    return text


def main(argv=None) -> int:
    # CI captures this output through a pipe, which on Windows means cp1252:
    # the log showed the dashes as mojibake, and a message quoting the
    # child's stderr could hold a character cp1252 cannot write at all.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--distribution", action="store_true",
                    help="build what you sell: licensing on, GPL models left out")
    ap.add_argument("--pubkey",
                    default=os.environ.get("YEWEE_PUBKEY", VENDOR_PUBLIC_KEY),
                    help="licence public key hex (defaults to the vendor key)")
    ap.add_argument("--version", default="",
                    help="version to stamp; defaults to yewee/__init__.py's "
                         "__version__, and a distribution build must match it")
    ap.add_argument("--print-version", action="store_true",
                    help="print the version a build would stamp, and exit")
    ap.add_argument("--keep-buildinfo", action="store_true",
                    help="leave yewee/_buildinfo.py in place afterwards")
    args = ap.parse_args(argv)

    declared = source_version()
    args.version = (args.version or declared).strip()
    if args.version.startswith("v"):
        args.version = args.version[1:]        # a tag name, v1.0.0
    if args.print_version:
        print(args.version)
        return 0
    # A sold build reports its version in crash reports, feedback and the
    # panel, and the shop's release page reads it off the tag. A tag that
    # disagrees with the code (v1.0 against 1.0.0, or a tag cut without
    # bumping __version__) would ship a build that misreports itself.
    if args.distribution and args.version != declared:
        return _fail(f"--version {args.version} does not match __version__ "
                     f"{declared} in yewee/__init__.py. Bump __version__ in "
                     "the commit you tag, or tag v" + declared + ".")

    if args.distribution and not args.pubkey:
        return _fail("A distribution build needs --pubkey, or nothing can be "
                     "activated. Get it from the Licence Admin.")
    if args.pubkey and len(args.pubkey) != 64:
        return _fail("--pubkey should be 64 hex characters.")

    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        return _fail("PyInstaller is missing:  pip install pyinstaller")

    kind = "DISTRIBUTION" if args.distribution else "internal"
    print(f"\n  building yewee {args.version} — {kind}")
    if args.distribution:
        print("  licensing: on (72-hour trial)   RVM: excluded (GPL-3.0)")
    else:
        print("  licensing: off (unrestricted)   RVM: included")

    # Third-party notices from the environment being packaged, so the file
    # lists exactly what ships. The licences of the bundled packages (MIT,
    # BSD, Apache, LGPL FFmpeg in OpenCV, MPL certifi) and the NDI SDK
    # licence all ask for their notices to travel with the binary.
    try:
        notices = third_party_notices()
    except RuntimeError as e:
        return _fail(f"Could not generate THIRD-PARTY-NOTICES.txt: {e}")
    NOTICES.write_text(notices, encoding="utf-8")

    write_buildinfo(args.distribution, args.pubkey, args.version)
    env = dict(os.environ)
    env["YEWEE_DISTRIBUTION"] = "1" if args.distribution else "0"
    env["YEWEE_VERSION"] = args.version

    t0 = time.time()
    cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
           "--distpath", str(BUILD / "dist"), "--workpath", str(BUILD / "work"),
           str(BUILD / "yewee.spec")]   # --specpath is invalid with a .spec
    try:
        proc = subprocess.run(cmd, cwd=ROOT, env=env)
    finally:
        if not args.keep_buildinfo:
            BUILDINFO.unlink(missing_ok=True)
    if proc.returncode != 0:
        return _fail("PyInstaller failed — see the output above.")

    # PyInstaller does not fail on a _buildinfo.py it cannot compile (a
    # cp1252 dash did exactly that): it logs the module as "invalid", leaves
    # it out and exits 0. Without it the app is a source checkout — licensing
    # dormant, running unrestricted — so a missing one is a failed build.
    if not _frozen_module_present("yewee._buildinfo"):
        return _fail("yewee._buildinfo is not in the bundle, so the app would "
                     "run unlicensed. See build/work/*/warn-*.txt.")

    out = BUILD / "dist" / ("Yewee.app" if sys.platform == "darwin" else "yewee")
    # count real files only — PyInstaller symlinks Frameworks into Resources,
    # and following those double-counts the whole bundle
    size = sum(f.stat().st_size for f in out.rglob("*")
               if f.is_file() and not f.is_symlink()) / 1e6
    print(f"\n  built in {time.time()-t0:.0f}s -> {out}  ({size:.0f} MB)")

    if not any(out.rglob("THIRD-PARTY-NOTICES.txt")):
        return _fail("THIRD-PARTY-NOTICES.txt is not in the bundle — the "
                     "licences of what ships must travel with it.")

    shipped = sorted({p.name for p in out.rglob("*.onnx")
                      if "datasets" not in str(p)})
    print("  models included: " + ", ".join(shipped))
    if args.distribution and any(n.startswith("rvm_") for n in shipped):
        return _fail("RVM is in a distribution build — it must not ship.")

    if sys.platform == "darwin":
        import plistlib
        plist = plistlib.loads((out / "Contents" / "Info.plist").read_bytes())
        # A background-only app has no window-server connection, so macOS
        # will not show it the camera prompt — it just denies, and the app
        # can never see a camera. PyInstaller sets this for console apps,
        # so it has to be turned off deliberately every time.
        if plist.get("LSBackgroundOnly"):
            return _fail("LSBackgroundOnly is set — the camera prompt can "
                         "never appear. Fix info_plist in yewee.spec.")
        if not plist.get("NSCameraUsageDescription"):
            return _fail("NSCameraUsageDescription is missing — macOS kills "
                         "the app when it opens a camera.")
        if not plist.get("NSLocalNetworkUsageDescription"):
            return _fail("NSLocalNetworkUsageDescription is missing — macOS "
                         "15 asks before NDI can reach the local network.")
        print("  Info.plist: foreground app, camera and local network described")

    if args.distribution:
        whose = ("the vendor key" if args.pubkey == VENDOR_PUBLIC_KEY
                 else "NOT the vendor key — nothing you issue will activate this")
        print(f"  licence key:  {args.pubkey[:16]}...  ({whose})")

    print("\n  next: sign and package (build/README.md)\n")
    return 0


def _frozen_module_present(name: str) -> bool:
    """Whether PyInstaller put module `name` into the archive it just built."""
    from PyInstaller.archive.readers import ZlibArchiveReader
    archives = list((BUILD / "work").glob("*/PYZ-*.pyz"))
    return bool(archives) and any(name in ZlibArchiveReader(str(p)).toc
                                  for p in archives)


def _fail(msg: str) -> int:
    print(f"\n  ERROR: {msg}\n", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
